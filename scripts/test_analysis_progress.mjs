import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const compiled = ts.transpileModule(readFileSync(new URL('../src/analysis-progress.ts', import.meta.url), 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
}).outputText;
const exports = {};
new Function('exports', compiled)(exports);
const { createAnalysisProgress, analysisDurationEstimate, recordAnalysisDuration, analysisTimingProfile, defaultAnalysisTimings, analysisTimingEstimate, recordAnalysisTimings } = exports;
const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
assert.equal(analysisDurationEstimate(storage, 'cpu-v5'), 80_000);
for (const duration of [72_000, 80_000, 84_000, 700_000]) recordAnalysisDuration(storage, 'cpu-v5', duration);
assert.equal(analysisDurationEstimate(storage, 'cpu-v5'), 82_000);
assert.equal(analysisDurationEstimate(storage, 'other-model'), 80_000);
recordAnalysisDuration(storage, 'cpu-v5', NaN);
assert.equal(analysisDurationEstimate(storage, 'cpu-v5'), 82_000);
const unavailable = { getItem() { throw Error('Unavailable'); }, setItem() { throw Error('Unavailable'); } };
assert.equal(analysisDurationEstimate(unavailable, 'cpu'), 80_000);
assert.doesNotThrow(() => recordAnalysisDuration(unavailable, 'cpu', 80_000));
const progress = createAnalysisProgress(0);
assert.equal(progress.sample(0).percentage, 0);
assert.ok(progress.sample(500_000).percentage < 20, 'Reading cannot imply AI has completed');
const beforeLoading = progress.sample(500_000).percentage;
progress.enter('loading', 500_000);
assert.equal(progress.sample(500_000).percentage, beforeLoading, 'Stage events do not jump the bar');
progress.enter('ai', 501_000);
let last = progress.sample(501_000).percentage;
for (const now of [510_000, 540_000, 580_000, 900_000]) {
  const sample = progress.sample(now);
  assert.ok(sample.percentage >= last && sample.percentage < 94);
  last = sample.percentage;
}
assert.match(progress.sample(900_000).hint, /longer than estimated/);
progress.setEstimate(200_000);
progress.enter('loading', 901_000);
assert.ok(progress.sample(901_000).percentage >= last, 'Late events and revised estimates cannot rewind progress');
progress.enter('finishing', 902_000);
assert.ok(progress.sample(50_000_000).percentage < 100, 'Only result completion may reach 100%');
for (let index = 0; index < 12; index++) recordAnalysisDuration(storage, 'bounded', 50_000 + index * 1_000);
const history = JSON.parse([...values.values()][0]);
assert.equal(history.bounded.length, 8);
const runtime = { model: 'qwen3:1.7b-q4_K_M', accelerator: 'CPU', cpu: 'test', cpu_only: true };
const fast = defaultAnalysisTimings(runtime);
const slow = defaultAnalysisTimings({ ...runtime, model: 'fishstop-qwen3:4b-finetuned-v5-q4_K_M' });
const gpu = defaultAnalysisTimings({ ...runtime, accelerator: 'GPU', cpu_only: false });
assert.ok(fast.ai < slow.ai && gpu.ai < fast.ai, 'Priors account for model size and execution');
assert.equal(analysisTimingProfile({ ...runtime, cpu_only: false, accelerator: 'CUDA' }), analysisTimingProfile({ ...runtime, cpu_only: false, accelerator: 'GPU' }), 'Warmup does not fragment history');
assert.notEqual(analysisTimingProfile(runtime), analysisTimingProfile({ ...runtime, model: '4b' }));
assert.notEqual(analysisTimingProfile(runtime), analysisTimingProfile({ ...runtime, cpu_optimization: { threads: 8, benchmarked_at: 123 } }));
const profile = analysisTimingProfile(runtime);
recordAnalysisTimings(storage, profile, { ...fast, ai: 20_000, identity: 4_000 });
assert.equal(analysisTimingEstimate(storage, profile, fast).ai, 20_000);
assert.deepEqual(analysisTimingEstimate(storage, 'other', slow), slow);
assert.deepEqual(analysisTimingEstimate(unavailable, profile, fast), fast);
assert.doesNotThrow(() => recordAnalysisTimings(unavailable, profile, fast));
const timed = createAnalysisProgress(0, { reading: 1_000, loading: 1_000, ai: 20_000, identity: 10_000, finishing: 500 });
timed.sample(1_000); timed.enter('loading', 1_000); timed.sample(2_000); timed.enter('ai', 2_000);
const aiEnd = timed.sample(22_000).percentage;
assert.ok(aiEnd > 55 && aiEnd < 75, 'Identity retains its measured share of work');
timed.enter('identity', 22_000);
assert.equal(timed.sample(22_000).percentage, aiEnd);
assert.ok(timed.sample(27_000).percentage > aiEnd && timed.sample(32_000).percentage < 100);
timed.enter('finishing', 32_000);
assert.deepEqual(timed.timings(32_500), { reading: 1_000, loading: 1_000, ai: 20_000, identity: 10_000, finishing: 500 });
const multi = createAnalysisProgress(0, fast);
multi.enter('ai', 0); multi.section(1, 3, 0);
const short = createAnalysisProgress(0, fast); short.enter('ai', 0);
assert.ok(multi.sample(30_000).percentage < short.sample(30_000).percentage, 'More sections slow the estimated fill');
multi.section(2, 3, 30_000);
multi.sample(60_000); multi.section(3, 3, 60_000);
multi.enter('identity', 90_000);
assert.equal(multi.timings(100_000).ai, 30_000, 'Learn per-section inference speed');
const longCpu = createAnalysisProgress(0, slow); longCpu.enter('ai', 0);
assert.ok(short.sample(30_000).percentage > longCpu.sample(30_000).percentage);
console.log('Analysis progress checks passed: measured phases, model/hardware profiles, section scaling, smooth monotonic progress, storage failures and completion cap.');
