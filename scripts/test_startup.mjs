import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const compiled = ts.transpileModule(readFileSync(new URL('../src/startup.ts', import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
const exports = {};
new Function('exports', compiled)(exports);
let finishHistory, finishWarmUp, complete = false;
const history = new Promise(resolve => { finishHistory = resolve; });
const warm = new Promise(resolve => { finishWarmUp = resolve; });
const ready = exports.prepareStartup(() => history, () => warm, 10).then(() => { complete = true; });
await new Promise(resolve => setTimeout(resolve, 25));
assert.equal(complete, false, 'A slow model cannot dismiss the splash before history is ready');
finishHistory();
await ready;
assert.equal(complete, true, 'Slow optional checks cannot hold the workspace after history loads');
finishWarmUp();
await exports.prepareStartup(async () => {}, async () => { throw new Error('Machine unavailable'); });
await exports.prepareStartup(async () => { throw new Error('Storage unavailable'); }, async () => {});
console.log('Startup checks passed: history readiness, bounded machine warm-up and failure recovery');
